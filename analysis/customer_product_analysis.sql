/*

# Analysis: Customer, Product, and Sales Performance

Purpose:
This script analyzes customer, product, and sales data from the Gold layer
to understand:
- Customer distribution by country and gender.
- Number of products within each category.
- Average product cost by category.
- Total revenue generated by each product category.
- Total revenue generated by each customer.
- Total quantity of items sold by country.

===============================================================================
*/

-- Count the total number of customers in each country.
-- Results are sorted from the country with the most customers to the least.
SELECT
country,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC

-- Count the total number of customers in each gender group.
-- Results are sorted from the largest customer group to the smallest.
SELECT
gender,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC

-- Count the total number of products in each category.
-- Results are sorted from categories with the most products to the least.
SELECT
category,
COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC

-- Calculate the average product cost for each category.
-- Results are sorted from the highest average cost to the lowest.
SELECT
category,
AVG(cost) AS average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY average_cost DESC

-- Calculate total revenue generated by each product category.
-- Combines the fact table with the product dimension to group sales by category.
SELECT
pro.category,
SUM(fact.sales_amount) AS total_revenue
FROM gold.fact_sales fact
LEFT JOIN gold.dim_products pro
ON pro.product_key = fact.product_key
GROUP BY pro.category
ORDER BY total_revenue DESC

-- Calculate the total revenue generated by each customer.
-- Combines sales data with customer details and sorts customers by revenue.
SELECT
cus.customer_key,
cus.first_name,
cus.last_name,
SUM(fact.sales_amount) AS total_revenue
FROM gold.fact_sales fact
LEFT JOIN gold.dim_customers cus
ON cus.customer_key = fact.customer_key
GROUP BY cus.customer_key,cus.first_name, cus.last_name
ORDER BY total_revenue DESC

-- Calculate the total number of items sold in each country.
-- Uses the quantity from the fact table and groups sales by customer country.
SELECT
cus.country,
SUM(fact.quantity) AS total_sold_items
FROM gold.fact_sales fact
LEFT JOIN gold.dim_customers cus
ON cus.customer_key = fact.customer_key
GROUP BY cus.country
ORDER BY total_sold_items DESC
